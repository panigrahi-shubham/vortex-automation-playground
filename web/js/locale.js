const key = 'vortex.locale';

export function language() {
  try { return localStorage.getItem(key) === 'hi' ? 'hi' : 'en'; }
  catch { return 'en'; }
}

export function setLanguage(value) {
  try { localStorage.setItem(key, value === 'hi' ? 'hi' : 'en'); }
  catch { /* browser storage is unavailable */ }
}

export function t(message, values = {}) {
  const translation = document.documentElement.lang === 'hi' && Object.hasOwn(messages, message) ? messages[message] : message;
  return translation.replace(/\{(\w+)\}/g, (match, name) => Object.hasOwn(values, name) ? values[name] : match);
}
